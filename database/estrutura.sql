-- Schema Oracle derivado dos fluxos funcionais atuais do projeto.
-- Execute conectado ao usuário PI2_APP depois de criar o usuário no serviço Oracle.

CREATE TABLE usuarios (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome VARCHAR2(100 CHAR) NOT NULL,
  login VARCHAR2(100 CHAR) NOT NULL,
  senha_hash VARCHAR2(200 CHAR) NOT NULL,
  perfil VARCHAR2(20 CHAR) NOT NULL,
  ativo NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uq_usuarios_login UNIQUE (login),
  CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('recepcao', 'enfermagem', 'medico')),
  CONSTRAINT ck_usuarios_ativo CHECK (ativo IN (0, 1))
);

CREATE TABLE pacientes (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome VARCHAR2(120 CHAR) NOT NULL,
  data_nascimento DATE NOT NULL,
  documento VARCHAR2(11 CHAR) NOT NULL,
  telefone VARCHAR2(20 CHAR),
  chave_cadastro CHAR(36) NOT NULL,
  criado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_pacientes_documento UNIQUE (documento),
  CONSTRAINT uq_pacientes_chave_cadastro UNIQUE (chave_cadastro)
);

CREATE INDEX idx_paciente_nome ON pacientes (nome);

CREATE TABLE atendimentos (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  paciente_id NUMBER NOT NULL,
  recepcionista_id NUMBER,
  situacao VARCHAR2(30 CHAR) DEFAULT 'aguardando_triagem' NOT NULL,
  chave_abertura CHAR(36) NOT NULL,
  aberto_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_atendimento_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
  CONSTRAINT fk_atendimento_usuario FOREIGN KEY (recepcionista_id) REFERENCES usuarios (id),
  CONSTRAINT uq_atendimento_chave UNIQUE (chave_abertura),
  CONSTRAINT ck_atendimento_situacao CHECK (
    situacao IN ('aguardando_triagem', 'aguardando_medico', 'em_atendimento', 'finalizado')
  )
);

CREATE INDEX idx_atendimento_situacao ON atendimentos (situacao);

CREATE UNIQUE INDEX uq_atendimento_ativo ON atendimentos (
  CASE WHEN situacao <> 'finalizado' THEN paciente_id END
);

CREATE TABLE prioridades_legais (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  atendimento_id NUMBER NOT NULL,
  declaracao VARCHAR2(20 CHAR) NOT NULL,
  data_doacao_sangue DATE,
  registrado_por NUMBER NOT NULL,
  registrado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_prioridade_atendimento UNIQUE (atendimento_id),
  CONSTRAINT fk_prioridade_atendimento FOREIGN KEY (atendimento_id) REFERENCES atendimentos(id),
  CONSTRAINT fk_prioridade_usuario FOREIGN KEY (registrado_por) REFERENCES usuarios(id),
  CONSTRAINT ck_prioridade_declaracao CHECK (declaracao IN ('sim', 'nao', 'nao_informado'))
);

CREATE TABLE categorias_prioridade_legal (
  prioridade_id NUMBER NOT NULL,
  categoria VARCHAR2(40 CHAR) NOT NULL,
  CONSTRAINT pk_categorias_prioridade PRIMARY KEY (prioridade_id, categoria),
  CONSTRAINT fk_categoria_prioridade FOREIGN KEY (prioridade_id) REFERENCES prioridades_legais(id),
  CONSTRAINT ck_categoria_prioridade CHECK (
    categoria IN (
      'pessoa_com_deficiencia',
      'pessoa_com_tea',
      'idoso_60_79',
      'gestante',
      'lactante',
      'pessoa_com_crianca_de_colo',
      'pessoa_obesa',
      'pessoa_com_mobilidade_reduzida',
      'idoso_80_mais',
      'doador_sangue'
    )
  )
);

CREATE TABLE historico_prioridades_legais (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  prioridade_id NUMBER NOT NULL,
  declaracao VARCHAR2(20 CHAR) NOT NULL,
  categorias_json VARCHAR2(500 CHAR) NOT NULL,
  data_doacao_sangue DATE,
  registrado_por NUMBER NOT NULL,
  registrado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_historico_prioridade FOREIGN KEY (prioridade_id) REFERENCES prioridades_legais(id),
  CONSTRAINT fk_hist_prioridade_usr FOREIGN KEY (registrado_por) REFERENCES usuarios(id),
  CONSTRAINT ck_hist_prio_decl
    CHECK (declaracao IN ('sim', 'nao', 'nao_informado'))
);

CREATE TABLE triagens (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  atendimento_id NUMBER NOT NULL,
  enfermeiro_id NUMBER NOT NULL,
  queixa VARCHAR2(500 CHAR) NOT NULL,
  pressao VARCHAR2(20 CHAR) NOT NULL,
  temperatura NUMBER(4,1) NOT NULL,
  frequencia NUMBER NOT NULL,
  saturacao NUMBER NOT NULL,
  classificacao VARCHAR2(20 CHAR) NOT NULL,
  criado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

  CONSTRAINT fk_triagem_atendimento
    FOREIGN KEY (atendimento_id)
    REFERENCES atendimentos(id),

  CONSTRAINT fk_triagem_enfermeiro
    FOREIGN KEY (enfermeiro_id)
    REFERENCES usuarios(id),

  CONSTRAINT ck_triagem_classificacao CHECK (
    classificacao IN ('Vermelho', 'Laranja', 'Amarelo', 'Verde', 'Azul')
  )
);

CREATE UNIQUE INDEX uq_triagem_atendimento ON triagens (atendimento_id);

CREATE TABLE consultas (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  atendimento_id NUMBER NOT NULL,
  medico_id NUMBER NOT NULL,
  registro_consulta CLOB NOT NULL,
  criado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_consulta_atendimento
    FOREIGN KEY (atendimento_id) REFERENCES atendimentos(id),
  CONSTRAINT fk_consulta_medico
    FOREIGN KEY (medico_id) REFERENCES usuarios(id)
);

CREATE INDEX idx_consultas_atendimento ON consultas (atendimento_id);

CREATE TABLE medicacoes (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  atendimento_id NUMBER NOT NULL,
  profissional_id NUMBER NOT NULL,
  medicacao VARCHAR2(120 CHAR) NOT NULL,
  dose VARCHAR2(80 CHAR) NOT NULL,
  via VARCHAR2(40 CHAR) NOT NULL,
  observacoes CLOB,
  criado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_medicacao_atendimento
    FOREIGN KEY (atendimento_id) REFERENCES atendimentos(id),
  CONSTRAINT fk_medicacao_profissional
    FOREIGN KEY (profissional_id) REFERENCES usuarios(id)
);

CREATE INDEX idx_medicacoes_atendimento ON medicacoes (atendimento_id);