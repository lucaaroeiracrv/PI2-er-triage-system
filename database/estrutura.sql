-- Schema Oracle derivado dos fluxos funcionais atuais do projeto.
-- Execute conectado ao usuário PI2_APP depois de criar o usuário no serviço Oracle.

CREATE TABLE usuarios (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome VARCHAR2(100 CHAR) NOT NULL,
  login VARCHAR2(100 CHAR) NOT NULL,
  senha_hash VARCHAR2(200 CHAR) NOT NULL,
  perfil VARCHAR2(20 CHAR) NOT NULL,
  ativo NUMBER(1) DEFAULT 1 NOT NULL,
  CONSTRAINT uq_usuarios_login UNIQUE (login),
  CONSTRAINT ck_usuarios_perfil CHECK (perfil IN ('recepcao', 'enfermagem', 'medico')),
  CONSTRAINT ck_usuarios_ativo CHECK (ativo IN (0, 1))
);

CREATE TABLE pacientes (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  nome VARCHAR2(120 CHAR) NOT NULL,
  data_nascimento DATE NOT NULL,
  documento VARCHAR2(11 CHAR) NOT NULL,
  telefone VARCHAR2(20 CHAR),
  chave_cadastro CHAR(36) NOT NULL,
  criado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT uq_pacientes_documento UNIQUE (documento),
  CONSTRAINT uq_pacientes_chave_cadastro UNIQUE (chave_cadastro)
);

CREATE INDEX idx_paciente_nome ON pacientes (nome);

CREATE TABLE atendimentos (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  paciente_id NUMBER NOT NULL,
  recepcionista_id NUMBER,
  situacao VARCHAR2(30 CHAR) DEFAULT 'aguardando_triagem' NOT NULL,
  chave_abertura CHAR(36) NOT NULL,
  aberto_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  CONSTRAINT fk_atendimento_paciente FOREIGN KEY (paciente_id) REFERENCES pacientes (id),
  CONSTRAINT fk_atendimento_usuario FOREIGN KEY (recepcionista_id) REFERENCES usuarios (id),
  CONSTRAINT uq_atendimento_chave UNIQUE (chave_abertura),
  CONSTRAINT ck_atendimento_situacao CHECK (
    situacao IN ('aguardando_triagem', 'aguardando_medico', 'em_atendimento', 'finalizado')
  )
);

CREATE INDEX idx_atendimento_situacao ON atendimentos (situacao);

CREATE UNIQUE INDEX uq_atendimento_ativo ON atendimentos (
  CASE WHEN situacao <> 'finalizado' THEN paciente_id END
);

