CREATE TABLE triagens (
  id NUMBER GENERATED BY DEFAULT ON NULL AS IDENTITY PRIMARY KEY,
  atendimento_id NUMBER NOT NULL,
  enfermeiro_id NUMBER NOT NULL,
  queixa VARCHAR2(500 CHAR) NOT NULL,
  pressao VARCHAR2(20 CHAR) NOT NULL,
  temperatura NUMBER(4,1) NOT NULL,
  frequencia NUMBER NOT NULL,
  saturacao NUMBER NOT NULL,
  classificacao VARCHAR2(20 CHAR) NOT NULL,
  criado_em TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,

  CONSTRAINT fk_triagem_atendimento
    FOREIGN KEY (atendimento_id)
    REFERENCES atendimentos(id),

  CONSTRAINT fk_triagem_enfermeiro
    FOREIGN KEY (enfermeiro_id)
    REFERENCES usuarios(id)
);